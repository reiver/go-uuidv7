package uuidv7_test

import (
	"testing"

	"github.com/reiver/go-uuidv7"
)

func TestString(t *testing.T) {
	tests := []struct{
		UUIDv7   [16]byte
		Expected string
	}{
		{
			UUIDv7: [16]byte{0x01,0x9e,0x0b,0xc7,0x40,0x7b,0x7c,0xd1,0xaa,0x11,0xbf,0x34,0xcb,0xbc,0xc5,0x53},
			Expected: "019e0bc7-407b-7cd1-aa11-bf34cbbcc553",
		},



		{
			UUIDv7: [16]byte{0x01,0x9e,0x0d,0x44,0x0b,0x23,0x7a,0x3f,0xb3,0xaf,0x7a,0x54,0xd9,0x2c,0xf8,0x50},
			Expected: "019e0d44-0b23-7a3f-b3af-7a54d92cf850",
		},



		{
			UUIDv7: [16]byte{0x01,0x9e,0x1a,0x5e,0xb6,0xd4,0x75,0x7c,0x88,0x90,0x9d,0x29,0x69,0xf2,0x9d,0x7e},
			Expected: "019e1a5e-b6d4-757c-8890-9d2969f29d7e",
		},



		{
			UUIDv7: [16]byte{0xfe,0xdc,0xba,0x98,0x76,0x54,0x73,0x21,0x80,0x24,0x68,0xac,0xef,0xdb,0x97,0x53},
			Expected: "fedcba98-7654-7321-8024-68acefdb9753",
		},



		{
			UUIDv7: [16]byte{0x00,0x00,0x00,0x00,0x00,0x00,0x70,0x00,0x80,0x00,0x00,0x00,0x00,0x00,0x00,0x00},
			Expected: "00000000-0000-7000-8000-000000000000",
		},
		{
			UUIDv7: [16]byte{0x00,0x00,0x00,0x00,0x00,0x00,0x70,0x00,0x90,0x00,0x00,0x00,0x00,0x00,0x00,0x00},
			Expected: "00000000-0000-7000-9000-000000000000",
		},
		{
			UUIDv7: [16]byte{0x00,0x00,0x00,0x00,0x00,0x00,0x70,0x00,0xa0,0x00,0x00,0x00,0x00,0x00,0x00,0x00},
			Expected: "00000000-0000-7000-a000-000000000000",
		},
		{
			UUIDv7: [16]byte{0x00,0x00,0x00,0x00,0x00,0x00,0x70,0x00,0xb0,0x00,0x00,0x00,0x00,0x00,0x00,0x00},
			Expected: "00000000-0000-7000-b000-000000000000",
		},



		{
			UUIDv7: [16]byte{0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00},
			Expected: "00000000-0000-0000-0000-000000000000",
		},
		{
			UUIDv7: [16]byte{0xED,0x7B,0xA4,0x70,0x8E,0x54,0x46,0x5E,0x82,0x5C,0x99,0x71,0x20,0x43,0xE0,0x1C},
			Expected: "ed7ba470-8e54-465e-825c-99712043e01c",
		},
		{
			UUIDv7: [16]byte{0xff,0xff,0xff,0xff,0xff,0xff,0xff,0xff,0xff,0xff,0xff,0xff,0xff,0xff,0xff,0xff},
			Expected: "ffffffff-ffff-ffff-ffff-ffffffffffff",
		},
	}

	for testNumber, test := range tests {
		actual := uuidv7.String(test.UUIDv7)

		expected := test.Expected

		if expected != actual {
			t.Errorf("For test #%d, the actual UUIDv7 string is not what was expected.", testNumber)
			t.Logf("EXPECTED: %s", expected)
			t.Logf("ACTUAL:   %s", actual)
			t.Logf("UUIDv7: %#v", test.UUIDv7)
			continue
		}
	}
}
