package uuidv7_test

import (
	"testing"

	"github.com/reiver/go-uuidv7"
)

func TestIs(t *testing.T) {
	tests := []struct{
		UUIDv7   [16]byte
		Expected bool
	}{
		{
			UUIDv7: uuidv7.Nada(),
			Expected: false,
		},
		{
			UUIDv7: uuidv7.Min(),
			Expected: true,
		},
		{
			UUIDv7: uuidv7.Max(),
			Expected: true,
		},



		{
			UUIDv7: [16]byte{0x01,0x9e,0x0b,0xc7,0x40,0x7b,0x7c,0xd1,0xaa,0x11,0xbf,0x34,0xcb,0xbc,0xc5,0x53},
			Expected: true,
		},
		{
			UUIDv7: uuidv7.MustParse("019e0bc7-407b-7cd1-aa11-bf34cbbcc553"),
			Expected: true,
		},
		{

		},



		{
			UUIDv7: [16]byte{0x01,0x9e,0x0d,0x44,0x0b,0x23,0x7a,0x3f,0xb3,0xaf,0x7a,0x54,0xd9,0x2c,0xf8,0x50},
			Expected: true,
		},
		{
			UUIDv7: uuidv7.MustParse("019e0d44-0b23-7a3f-b3af-7a54d92cf850"),
			Expected: true,
		},



		{
			UUIDv7: [16]byte{0x01,0x9e,0x1a,0x5e,0xb6,0xd4,0x75,0x7c,0x88,0x90,0x9d,0x29,0x69,0xf2,0x9d,0x7e},
			Expected: true,
		},
		{
			UUIDv7: uuidv7.MustParse("019e1a5e-b6d4-757c-8890-9d2969f29d7e"),
			Expected: true,
		},



		{
			UUIDv7: [16]byte{0xfe,0xdc,0xba,0x98,0x76,0x54,0x73,0x21,0x80,0x24,0x68,0xac,0xef,0xdb,0x97,0x53},
			Expected: true,
		},
		{
			UUIDv7: uuidv7.MustParse("fedcba98-7654-7321-8024-68acefdb9753"),
			Expected: true,
		},



		{
			UUIDv7: [16]byte{0x00,0x00,0x00,0x00,0x00,0x00,0x70,0x00,0x80,0x00,0x00,0x00,0x00,0x00,0x00,0x00},
			Expected: true,
		},
		{
			UUIDv7: uuidv7.MustParse("00000000-0000-7000-8000-000000000000"),
			Expected: true,
		},

		{
			UUIDv7: [16]byte{0x00,0x00,0x00,0x00,0x00,0x00,0x70,0x00,0x90,0x00,0x00,0x00,0x00,0x00,0x00,0x00},
			Expected: true,
		},
		{
			UUIDv7: uuidv7.MustParse("00000000-0000-7000-9000-000000000000"),
			Expected: true,
		},

		{
			UUIDv7: [16]byte{0x00,0x00,0x00,0x00,0x00,0x00,0x70,0x00,0xa0,0x00,0x00,0x00,0x00,0x00,0x00,0x00},
			Expected: true,
		},
		{
			UUIDv7: uuidv7.MustParse("00000000-0000-7000-a000-000000000000"),
			Expected: true,
		},

		{
			UUIDv7: [16]byte{0x00,0x00,0x00,0x00,0x00,0x00,0x70,0x00,0xb0,0x00,0x00,0x00,0x00,0x00,0x00,0x00},
			Expected: true,
		},
		{
			UUIDv7: uuidv7.MustParse("00000000-0000-7000-b000-000000000000"),
			Expected: true,
		},



		{
			UUIDv7: [16]byte{0x11,0x11,0x11,0x11,0x11,0x11,0x11,0x11,0x11,0x11,0x11,0x11,0x11,0x11,0x11,0x11},
			Expected: false,
		},
		{
			UUIDv7: [16]byte{0x22,0x22,0x22,0x22,0x22,0x22,0x22,0x22,0x22,0x22,0x22,0x22,0x22,0x22,0x22,0x22},
			Expected: false,
		},
		{
			UUIDv7: [16]byte{0x33,0x33,0x33,0x33,0x33,0x33,0x33,0x33,0x33,0x33,0x33,0x33,0x33,0x33,0x33,0x33},
			Expected: false,
		},
		{
			UUIDv7: [16]byte{0x44,0x44,0x44,0x44,0x44,0x44,0x44,0x44,0x44,0x44,0x44,0x44,0x44,0x44,0x44,0x44},
			Expected: false,
		},
		{
			UUIDv7: [16]byte{0x55,0x55,0x55,0x55,0x55,0x55,0x55,0x55,0x55,0x55,0x55,0x55,0x55,0x55,0x55,0x55},
			Expected: false,
		},
		{
			UUIDv7: [16]byte{0x66,0x66,0x66,0x66,0x66,0x66,0x66,0x66,0x66,0x66,0x66,0x66,0x66,0x66,0x66,0x66},
			Expected: false,
		},
		{
			UUIDv7: [16]byte{0x77,0x77,0x77,0x77,0x77,0x77,0x77,0x77,0x77,0x77,0x77,0x77,0x77,0x77,0x77,0x77},
			Expected: false,
		},
		{
			UUIDv7: [16]byte{0x88,0x88,0x88,0x88,0x88,0x88,0x88,0x88,0x88,0x88,0x88,0x88,0x88,0x88,0x88,0x88},
			Expected: false,
		},
		{
			UUIDv7: [16]byte{0x99,0x99,0x99,0x99,0x99,0x99,0x99,0x99,0x99,0x99,0x99,0x99,0x99,0x99,0x99,0x99},
			Expected: false,
		},
		{
			UUIDv7: [16]byte{0xaa,0xaa,0xaa,0xaa,0xaa,0xaa,0xaa,0xaa,0xaa,0xaa,0xaa,0xaa,0xaa,0xaa,0xaa,0xaa},
			Expected: false,
		},
		{
			UUIDv7: [16]byte{0xbb,0xbb,0xbb,0xbb,0xbb,0xbb,0xbb,0xbb,0xbb,0xbb,0xbb,0xbb,0xbb,0xbb,0xbb,0xbb},
			Expected: false,
		},
		{
			UUIDv7: [16]byte{0xcc,0xcc,0xcc,0xcc,0xcc,0xcc,0xcc,0xcc,0xcc,0xcc,0xcc,0xcc,0xcc,0xcc,0xcc,0xcc},
			Expected: false,
		},
		{
			UUIDv7: [16]byte{0xdd,0xdd,0xdd,0xdd,0xdd,0xdd,0xdd,0xdd,0xdd,0xdd,0xdd,0xdd,0xdd,0xdd,0xdd,0xdd},
			Expected: false,
		},
		{
			UUIDv7: [16]byte{0xee,0xee,0xee,0xee,0xee,0xee,0xee,0xee,0xee,0xee,0xee,0xee,0xee,0xee,0xee,0xee},
			Expected: false,
		},
		{
			UUIDv7: [16]byte{0xff,0xff,0xff,0xff,0xff,0xff,0xff,0xff,0xff,0xff,0xff,0xff,0xff,0xff,0xff,0xff},
			Expected: false,
		},



		{
			UUIDv7: [16]byte{0xED,0x7B,0xA4,0x70,0x8E,0x54,0x46,0x5E,0x82,0x5C,0x99,0x71,0x20,0x43,0xE0,0x1C},
			Expected: false,
		},
	}

	for testNumber, test := range tests {
		actual := uuidv7.Is(test.UUIDv7)

		expected := test.Expected

		if expected != actual {
			t.Errorf("For test #%d, the actual is-UUIDv7 is not what was expected.", testNumber)
			t.Logf("EXPECTED: %t", expected)
			t.Logf("ACTUAL:   %t", actual)
			t.Logf("UUIDv7: %s", uuidv7.String(test.UUIDv7))
			t.Logf("UUIDv7: %#v", test.UUIDv7)
			continue
		}
	}
}
